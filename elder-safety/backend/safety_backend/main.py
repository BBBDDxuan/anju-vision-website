import asyncio
from contextlib import asynccontextmanager
from datetime import datetime
import hmac
import io
from pathlib import Path
from uuid import uuid4
from fastapi import FastAPI, Depends, HTTPException, UploadFile, File, Form, Query
from fastapi.responses import FileResponse, JSONResponse
from fastapi.security import HTTPBearer, HTTPAuthorizationCredentials
from PIL import Image, UnidentifiedImageError
from .config import Settings
from .repository import Repository, Missing, Conflict, stamp
from .providers import Providers
from .worker import Worker
from .schemas import (DeviceIn, DeviceOut, EventIn, EventOut, EventType, PushIn, Preferences, EvidenceOut, TokenOut, Result, EvidenceAttach)

security = HTTPBearer(auto_error=False)

def create_app(settings=None, providers_factory=Providers):
    s = (settings or Settings.from_env()).validate()
    repo = Repository(s)
    providers = providers_factory(s, repo)
    worker = Worker(repo, providers)
    tasks = []

    @asynccontextmanager
    async def lifespan(app):
        if s.worker_enabled:
            tasks.extend([asyncio.create_task(worker.run(("notify", "escalate"))), asyncio.create_task(worker.run(("review",))), asyncio.create_task(worker.monitor())])
        yield
        for task in tasks:
            task.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)
        # Blocking provider calls use bounded timeouts; the process waits for executor threads on exit.
        repo.engine.dispose()

    app = FastAPI(title="安居视界安全监护", version="0.1.0", lifespan=lifespan)
    app.state.repo, app.state.worker, app.state.settings = repo, worker, s

    @app.exception_handler(Missing)
    async def missing(request, exc):
        return JSONResponse(status_code=404, content={"detail": str(exc)})

    @app.exception_handler(Conflict)
    async def conflict(request, exc):
        return JSONResponse(status_code=409, content={"detail": str(exc)})

    @app.exception_handler(Exception)
    async def server_error(request, exc):
        import logging
        logging.getLogger(__name__).error("API failure: %s", type(exc).__name__)
        return JSONResponse(status_code=500, content={"detail": "Internal service error"})

    def identity(auth: HTTPAuthorizationCredentials | None = Depends(security)):
        if auth is None:
            raise HTTPException(401, "Bearer token required", headers={"WWW-Authenticate": "Bearer"})
        token = auth.credentials
        if hmac.compare_digest(token, s.user_token):
            return ("user", None)
        for device_id, value in s.device_tokens.items():
            if hmac.compare_digest(token, value):
                return ("device", device_id)
        raise HTTPException(401, "Invalid credentials")

    def user(who=Depends(identity)):
        if who[0] != "user":
            raise HTTPException(403, "User credentials required")

    def device(who=Depends(identity)):
        if who[0] != "device":
            raise HTTPException(403, "Device credentials required")
        return who[1]

    def own(actual, expected):
        if actual != expected:
            raise HTTPException(403, "Device identity mismatch")

    @app.get("/health")
    def health():
        return {"status": "ok", "review_mode": s.review_mode, "push_mode": s.push_mode}

    @app.post("/api/v1/devices/register", response_model=DeviceOut)
    def register(body: DeviceIn, device_id=Depends(device)):
        own(body.device_id, device_id)
        return repo.register(body.device_id, body.name)

    @app.get("/api/v1/devices", response_model=list[DeviceOut], dependencies=[Depends(user)])
    def devices():
        return repo.devices_list()

    @app.get("/api/v1/devices/{device_id}/status", response_model=DeviceOut, dependencies=[Depends(user)])
    def device_status(device_id: str):
        return repo.device(device_id)

    @app.post("/api/v1/devices/{device_id}/heartbeat", response_model=DeviceOut)
    def heartbeat(device_id: str, authorized=Depends(device)):
        own(device_id, authorized)
        return repo.heartbeat(device_id)

    @app.post("/api/v1/events", response_model=EventOut)
    def submit(body: EventIn, device_id=Depends(device)):
        own(body.device_id, device_id)
        if body.event_type == "device_offline":
            raise HTTPException(422, "Device offline events are generated by the heartbeat monitor")
        return repo.ingest(body)

    @app.get("/api/v1/events", response_model=list[EventOut], dependencies=[Depends(user)])
    def events(event_type: EventType | None = None, state: str | None = Query(default=None, pattern="^(detected|notified|acknowledged|resolved)$"), limit: int = Query(100, ge=1, le=200), offset: int = Query(0, ge=0), after: datetime | None = None, before: datetime | None = None):
        for t in (after, before):
            if t is not None and t.utcoffset() is None:
                raise HTTPException(422, "Timezone required for history filters")
        if after and before and after > before:
            raise HTTPException(422, "after must be before before")
        return repo.list_events(event_type, state, limit, offset, after, before)

    @app.get("/api/v1/events/{event_id}", response_model=EventOut, dependencies=[Depends(user)])
    def get_event(event_id: str):
        return repo.get_event(event_id)

    @app.post("/api/v1/events/{event_id}/evidence", response_model=EventOut)
    def attach_evidence(event_id: str, body: EvidenceAttach, device_id=Depends(device)):
        try:
            return repo.attach_evidence(event_id, device_id, body)
        except PermissionError:
            raise HTTPException(403, "Device identity mismatch") from None

    @app.post("/api/v1/events/{event_id}/ack", response_model=EventOut, dependencies=[Depends(user)])
    def ack(event_id: str):
        return repo.change_event(event_id, "ack")

    @app.post("/api/v1/events/{event_id}/resolve", response_model=EventOut, dependencies=[Depends(user)])
    def resolve(event_id: str):
        return repo.change_event(event_id, "resolve")

    @app.delete("/api/v1/events/{event_id}", response_model=Result, dependencies=[Depends(user)])
    def remove(event_id: str):
        repo.delete_event(event_id)
        return {"ok": True}

    @app.post("/api/v1/evidence", response_model=EvidenceOut)
    async def upload(device_id: str = Form(...), file: UploadFile = File(...), authorized=Depends(device)):
        own(device_id, authorized)
        repo.device(device_id)
        content = await file.read(s.max_upload_bytes + 1)
        await file.close()
        if not content or len(content) > s.max_upload_bytes:
            raise HTTPException(413, "Evidence size exceeds configured limit or is empty")
        if file.content_type in {"image/jpeg", "image/png"}:
            try:
                with Image.open(io.BytesIO(content)) as image:
                    if image.format not in {"JPEG", "PNG"} or image.width * image.height > 16000000:
                        raise ValueError("Invalid image")
                    # Re-encode strips metadata and avoids trusting the client MIME type.
                    image.load()
                    buffer = io.BytesIO()
                    image.convert("RGB").save(buffer, "JPEG", quality=90)
                    content = buffer.getvalue()
                suffix, media_type = ".jpg", "image/jpeg"
            except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError):
                raise HTTPException(415, "Invalid image") from None
        elif file.content_type == "video/mp4" and len(content) >= 12 and content[4:8] == b"ftyp":
            suffix, media_type = ".mp4", "video/mp4"
        else:
            raise HTTPException(415, "Only JPEG/PNG images and MP4 clips are accepted")
        directory = s.data_dir / "evidence"
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / (uuid4().hex + suffix)
        path.write_bytes(content)
        try:
            item = repo.add_evidence(device_id, path, media_type)
            return {"evidence_id": item["evidence_id"], "expires_at": item["expires_at"]}
        except Exception:
            path.unlink(missing_ok=True)
            raise

    @app.get("/api/v1/evidence/{evidence_id}", dependencies=[Depends(user)])
    def evidence(evidence_id: str):
        item = repo.get_evidence(evidence_id)
        if item["expires_at"] <= stamp():
            raise HTTPException(410, "Evidence expired")
        path = Path(item["path"]).resolve()
        if not path.is_relative_to(s.data_dir / "evidence") or not path.is_file():
            raise HTTPException(404, "Evidence unavailable")
        return FileResponse(path, media_type=item["media_type"], headers={"Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"})

    @app.post("/api/v1/push-tokens", response_model=TokenOut, dependencies=[Depends(user)])
    def push_token(body: PushIn):
        return repo.register_token(body)

    @app.delete("/api/v1/push-tokens/{token_id}", response_model=Result, dependencies=[Depends(user)])
    def delete_token(token_id: str):
        repo.delete_token(token_id)
        return {"ok": True}

    @app.get("/api/v1/preferences", response_model=Preferences, dependencies=[Depends(user)])
    def preferences():
        return repo.get_preferences()

    @app.put("/api/v1/preferences", response_model=Preferences, dependencies=[Depends(user)])
    def save_preferences(body: Preferences):
        return repo.save_preferences(body)

    return app
